// Generates src/main/resources/db/migration/V3__import_final_tables.sql from
// the TSV exports in Old/MovieConnect/final_tables (Movie.tsv, Actor.tsv,
// MovieActor.tsv - headerless, IMDb-derived numeric IDs).
//
// Usage (from backend/):  node scripts/generate-v3-import.mjs [tsvDir]
//
// NOTE: V3 is a Flyway migration. Once it has been applied anywhere, do not
// regenerate it in place (the checksum would change) - write a new version.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tsvDir = resolve(process.argv[2] ?? join(backendDir, '..', 'Old', 'MovieConnect', 'final_tables'));
const outFile = join(backendDir, 'src', 'main', 'resources', 'db', 'migration', 'V3__import_final_tables.sql');
const CHUNK_SIZE = 1000;

function readTsv(name, expectedColumns) {
    const text = readFileSync(join(tsvDir, name), 'utf8').replace(/^﻿/, '');
    return text.split(/\r?\n/).filter(line => line.length > 0).map((line, i) => {
        const cols = line.split('\t');
        if (cols.length !== expectedColumns) {
            throw new Error(`${name}:${i + 1}: expected ${expectedColumns} columns, got ${cols.length}`);
        }
        return cols;
    });
}

function int(value, { nullable = false } = {}) {
    if (value === '' && nullable) return 'NULL';
    if (!/^\d+$/.test(value)) throw new Error(`Not an integer: "${value}"`);
    return value;
}

function decimal(value) {
    if (value === '') return 'NULL';
    if (!/^\d+(\.\d+)?$/.test(value)) throw new Error(`Not a decimal: "${value}"`);
    return value;
}

function str(value) {
    // MySQL treats backslash as an escape character in string literals.
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
}

function gender(value) {
    if (value === '') return 'NULL';
    if (value !== 'm' && value !== 'f') throw new Error(`Unexpected gender: "${value}"`);
    return str(value);
}

function inserts(header, rows) {
    const out = [];
    for (let i = 0; i < rows.length; i += CHUNK_SIZE) {
        out.push(`${header}\n    ${rows.slice(i, i + CHUNK_SIZE).join(',\n    ')};\n`);
    }
    return out.join('\n');
}

// Movie.tsv: id, title, original_title (dropped), release_year, runtime_minutes, num_votes, average_rating
const movies = readTsv('Movie.tsv', 7);
const movieRows = movies.map(([id, title, , year, runtime, votes, rating]) =>
    `(${int(id)}, ${str(title)}, ${int(year)}, ${int(runtime, { nullable: true })}, ${decimal(rating)}, ${int(votes)})`);

// Actor.tsv: id, name, birth_year, death_year, gender (m/f)
const actors = readTsv('Actor.tsv', 5);
const actorRows = actors.map(([id, name, birth, death, g]) =>
    `(${int(id)}, ${str(name)}, ${int(birth, { nullable: true })}, ${int(death, { nullable: true })}, ${gender(g)})`);

// MovieActor.tsv: movie_id, actor_id, importance, category (dropped - redundant with actor.gender)
// Rows whose movie or actor isn't in the other files would violate the FKs, so skip them.
const movieIds = new Set(movies.map(r => r[0]));
const actorIds = new Set(actors.map(r => r[0]));
const castAll = readTsv('MovieActor.tsv', 4);
const cast = castAll.filter(([movieId, actorId]) => movieIds.has(movieId) && actorIds.has(actorId));
const castRows = cast.map(([movieId, actorId, importance]) =>
    `(${int(movieId)}, ${int(actorId)}, ${int(importance)}, NULL)`);
const skipped = castAll.length - cast.length;

const sql = `-- GENERATED by scripts/generate-v3-import.mjs from Old/MovieConnect/final_tables.
-- Do not edit by hand. Do not regenerate once applied - add a new migration instead.
--
-- Replaces the V2 sample dataset with the MovieConnect dataset (IMDb-derived,
-- IDs are the numeric part of IMDb's tt/nm identifiers):
--   ${movieRows.length} movies, ${actorRows.length} actors, ${castRows.length} cast rows
--   (${skipped} cast rows skipped because their actor/movie is not in the export).
-- Dropped source columns: Movie.original_title, MovieActor.category.
-- character_name is not in the source data, so it is NULL for every row.

ALTER TABLE actor ADD COLUMN gender CHAR(1) NULL;

-- V2's hand-assigned IDs (1..37 actors, 1..14 movies) collide with the IMDb
-- IDs used below, so clear the sample data first.
DELETE FROM movie_actor;
DELETE FROM movie;
DELETE FROM actor;

${inserts('INSERT INTO movie (id, title, release_year, runtime_minutes, average_rating, num_votes) VALUES', movieRows)}
${inserts('INSERT INTO actor (id, name, birth_year, death_year, gender) VALUES', actorRows)}
${inserts('INSERT INTO movie_actor (movie_id, actor_id, importance, character_name) VALUES', castRows)}`;

writeFileSync(outFile, sql, 'utf8');
console.log(`Wrote ${outFile}`);
console.log(`movies=${movieRows.length} actors=${actorRows.length} cast=${castRows.length} skipped=${skipped}`);
